/** Качающийся бас: 8 восьмых чередованием двух питчей с указанного бита. */
function spreadAlternating(low: number, high: number, startBeat: number): Array<readonly [number, number, number]> {
  const tuples: Array<readonly [number, number, number]> = [];
  for (let i = 0; i < 8; i++) {
    tuples.push([i % 2 === 0 ? low : high, startBeat + i * 0.5, 0.5]);
  }
  return tuples;
}
